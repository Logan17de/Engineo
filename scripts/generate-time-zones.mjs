import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const zones = JSON.parse(
  execFileSync(
    process.env.ENGINEO_SCHEDULER_BIN ?? "target/release/engineo-schedule",
    ["--time-zones"],
    { encoding: "utf8", timeout: 10_000, maxBuffer: 1024 * 1024 },
  ),
);
if (!Array.isArray(zones) || zones.length < 400 || zones.some((zone) => typeof zone !== "string")) {
  throw new Error("Engine returned an invalid time-zone catalogue");
}
const content = `// Generated by scripts/generate-time-zones.mjs from the Rust engine.\n// Regenerate after changing chrono-tz; CI checks agreement with the real binary.\nexport const ENGINE_TIME_ZONES: readonly string[] = [\n${zones.map((zone) => `  ${JSON.stringify(zone)},`).join("\n")}\n];\n`;
const path = new URL("../packages/contracts/src/time-zones.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== content)
    throw new Error("Time-zone contract differs from the engine; regenerate it");
} else writeFileSync(path, content);
